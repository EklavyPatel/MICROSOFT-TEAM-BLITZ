"""Generate a single downloadable HTML file using only Python's standard library."""

from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent


def build():
    html = (ROOT / "index.html").read_text()
    css = (ROOT / "styles.css").read_text()
    api = (ROOT / "api.js").read_text()
    app = (ROOT / "app.js").read_text()
    api = re.sub(r"^export (?=(?:class|async function|function)\b)", "", api, flags=re.MULTILINE)
    app, count = re.subn(r'^import \{ request, ApiError, createPoller \} from "\./api\.js";\n', "", app)
    if count != 1:
        raise ValueError("The app import changed; update this bundler before generating HTML.")
    stylesheet = '<link rel="stylesheet" href="styles.css" />'
    script = '<script type="module" src="app.js"></script>'
    if html.count(stylesheet) != 1 or html.count(script) != 1:
        raise ValueError("The entry HTML changed; update this bundler's asset markers.")
    html = html.replace(stylesheet, "<style>\n" + css + "\n</style>").replace(script, "")
    code = '"use strict";\n(() => {\n' + api + "\n" + app + "\n})();"
    code = re.sub(r"</script", r"<\\/script", code, flags=re.IGNORECASE)
    html = html.replace("</body>", "<script>\n" + code + "\n</script>\n</body>")
    html = "\n".join(line.rstrip() for line in html.splitlines()) + "\n"
    output = ROOT / "watchcircle.html"
    output.write_text("<!-- Generated by build_standalone.py; edit the source files instead. -->\n" + html)
    print(f"Generated {output.name} ({output.stat().st_size:,} bytes)")


if __name__ == "__main__":
    build()
